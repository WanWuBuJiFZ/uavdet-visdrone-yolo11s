_current = DEFAULT_LANGUAGE


def is_supported(language: str) -> bool:
    """True when ``language`` is one of :data:`LANGUAGES`."""
    return str(language) in LANGUAGES


def set_language(language: str) -> str:
    """Switch the UI language (``zh`` or ``en``); returns the effective value."""
    global _current
    _current = str(language) if is_supported(language) else DEFAULT_LANGUAGE
    return _current


def get_language() -> str:
    return _current


def next_language(language: str | None = None) -> str:
    """The other language (used by the toggle button)."""
    current = language or _current
    return "en" if current == "zh" else "zh"


def tr(text: str) -> str:
    """Translate a Chinese UI string; unknown strings fall back to themselves."""
    if _current == "en":
        return _EN.get(text, text)
    return text
